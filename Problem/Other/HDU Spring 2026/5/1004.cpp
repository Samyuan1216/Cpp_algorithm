void solve()
{
    i64 n;
    std::cin >> n;

    i64 ans = 0, power = 2;
    while (power <= n)
    {
        i64 M = n / power;
        ans += M * (n + 1) - power * (1 + M) * M / 2;

        power <<= 1;
    }

    std::cout << ans << "\n";
}

int main()
{
    std::cin.tie(nullptr)->sync_with_stdio(false);

    int t = 1;
    std::cin >> t;
    while (t--)
    {
        solve();
    }
}
