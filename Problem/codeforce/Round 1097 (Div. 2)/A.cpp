void solve()
{
    int n;
    std::cin >> n;

    std::vector<i64> arr(n);
    for (auto &x: arr)
    {
        std::cin >> x;
    }

    int ans = (arr[n - 1] > 0? 1: 0);
    for (int i = n - 2; i >= 0; --i)
    {
        if (arr[i + 1] > 0)
        {
            arr[i] += arr[i + 1];
        }

        if (arr[i] > 0)
        {
            ++ans;
        }
    }

    std::cout << ans << "\n";
}

int main()
{
    std::cin.tie(nullptr)->sync_with_stdio(false);

    int t = 1;
    std::cin >> t;
    while (t--)
    {
        solve();
    }
}
