void solve()
{
    int n;
    std::cin >> n;

    std::vector<int> arr(n);
    for (auto &x: arr)
    {
        std::cin >> x;
    }

    ranges::sort(arr, std::greater());

    i64 h = 0, w = 0;
    for (auto &x: arr)
    {
        if (h <= w)
        {
            h += 1ll << x;
        }
        else
        {
            w += 1ll << x;
        }
    }

    std::cout << h * w << "\n";
}

int main()
{
    std::cin.tie(nullptr)->sync_with_stdio(false);

    int t = 1;
    std::cin >> t;
    while (t--)
    {
        solve();
    }
}