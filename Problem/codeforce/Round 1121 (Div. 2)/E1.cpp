template <int MOD>
struct ModInt
{
    int val;

    ModInt(i64 v = 0)
    {
        v %= MOD;
        if (v < 0)
        {
            v += MOD;
        }
        val = static_cast<int>(v);
    }

    ModInt pow(i64 p) const
    {
        ModInt res = 1, a = *this;
        while (p > 0)
        {
            if (p & 1)
            {
                res *= a;
            }
            a *= a;
            p >>= 1;
        }
        return res;
    }

    ModInt inv() const
    {
        return pow(MOD - 2);
    }

    ModInt& operator+=(const ModInt& other)
    {
        val += other.val;
        if (val >= MOD)
        {
            val -= MOD;
        }
        return *this;
    }

    ModInt& operator-=(const ModInt& other)
    {
        val -= other.val;
        if (val < 0)
        {
            val += MOD;
        }
        return *this;
    }

    ModInt& operator*=(const ModInt& other)
    {
        val = static_cast<int>(1LL * val * other.val % MOD);
        return *this;
    }

    ModInt& operator/=(const ModInt& other)
    {
        return *this *= other.inv();
    }

    ModInt operator-() const
    {
        return ModInt(val == 0 ? 0 : MOD - val);
    }

    ModInt& operator++()
    {
        return *this += 1;
    }

    ModInt& operator--()
    {
        return *this -= 1;
    }

    ModInt operator++(int)
    {
        ModInt temp = *this;
        *this += 1;
        return temp;
    }

    ModInt operator--(int)
    {
        ModInt temp = *this; 
        *this -= 1; 
        return temp;
    }

    friend ModInt operator+(ModInt a, const ModInt& b)
    {
        return a += b;
    }

    friend ModInt operator-(ModInt a, const ModInt& b)
    {
        return a -= b;
    }

    friend ModInt operator*(ModInt a, const ModInt& b)
    {
        return a *= b;
    }

    friend ModInt operator/(ModInt a, const ModInt& b)
    {
        return a /= b;
    }

    auto operator<=>(const ModInt& other) const = default;

    friend std::istream& operator>>(std::istream& is, ModInt& m)
    {
        i64 v;
        is >> v;
        m = ModInt(v);
        return is;
    }

    friend std::ostream& operator<<(std::ostream& os, const ModInt& m)
    {
        return os << m.val;
    }
};

void solve()
{
    using mint = ModInt<998244353>;
    static auto dp = []() -> std::vector<std::vector<mint>>
    {
        std::vector<bool> visited(3010);
        std::vector<i64> r(3010, 1);

        for (int i = 2; i <= 3000; ++i)
        {
            if (visited[i])
            {
                continue;
            }

            visited[i] = true;
            for (int j = i; j <= 3000; j += i)
            {
                visited[j] = true;
                r[j] *= i;
            }
        }

        std::vector dp(3010, std::vector<mint>(3010, 1e9));
        for (int x = 1; x <= 3000; ++x)
        {
            dp[1][x] = 1;
        }

        for (int x = 2; x <= 3000; ++x)
        {
            dp[x][x] = x;
            for (int y = x + 1; y <= 3000; ++y)
            {
                dp[x][y] = (x % r[y] == 0? dp[x - 1][y - 1]: dp[x][y - 1]);
            }
        }

        return dp;
    } ();

    int n;
    std::cin >> n;

    std::vector<i64> arr(n);
    for (auto &x: arr)
    {
        std::cin >> x;
    }

    ranges::sort(arr);

    mint ans = 0;
    for (int l = 0; l < n; ++l)
    {
        ans += arr[l];
        for (int r = l + 1; r < n; ++r)
        {
            ans += dp[arr[l]][arr[r]] * mint(2).pow(r - l - 1);
        }
    }

    std::cout << ans << "\n";
}

int main()
{
    std::cin.tie(nullptr)->sync_with_stdio(false);

    int t = 1;
    std::cin >> t;
    while (t--)
    {
        solve();
    }
}
